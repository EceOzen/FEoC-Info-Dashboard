#!/usr/bin/env python3
"""
Generate one EXAMPLE panel per ready-made asset format, so you can see how
each looks on the dashboard and copy the pattern for real figures.

Everything here is SYNTHETIC data — these are pipeline demos, not science.
Panels are written with status="draft" and panel_id "example_*", so they
never reach the live site. Preview them locally:

    pip install matplotlib plotly bokeh nbformat nbconvert ipykernel   # whichever you have is fine
    python examples/make_asset_examples.py
    python scripts/validate_panel.py
    python scripts/build_manifest.py --include-drafts
    python scripts/build_assets.py          # PDF preview, needs pdftoppm
    cd site && python3 -m http.server 8000

Remove them again with:  python examples/make_asset_examples.py --clean

Each example calls methods/generic/from_asset.py exactly as a scientist
would, so the commands printed below double as copy-paste templates.
Formats whose library isn't installed are skipped with a note.
"""

from __future__ import annotations

import argparse
import json
import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FROM_ASSET = REPO / "methods" / "generic" / "from_asset.py"
COMMON = [
    "--author", "example-bot",
    "--status", "draft",
    "--method-note", "Synthetic demo data generated by examples/make_asset_examples.py",
    "--source", "examples/make_asset_examples.py (synthetic, not science)",
]

YEARS = list(range(1850, 2024))


def co2_erf(year: int) -> float:
    # smooth synthetic curve, roughly the right shape
    c = 285 + 135 * (1 / (1 + math.exp(-(year - 1985) / 28)))
    return 5.35 * math.log(c / 285)


def volcanic_pulse(year: int) -> float:
    eruptions = {1883: 1.0, 1902: 0.5, 1963: 0.7, 1982: 0.6, 1991: 1.1}
    return -sum(a * 3.0 * math.exp(-(year - y) / 1.2) for y, a in eruptions.items() if year >= y)


def run(args: list[str]) -> None:
    cmd = [sys.executable, str(FROM_ASSET)] + args + COMMON
    print("$", " ".join(a if " " not in a else repr(a) for a in cmd[1:]))
    subprocess.run(cmd, check=True, cwd=REPO)


def skip(fmt: str, lib: str) -> None:
    print(f"-- skipping {fmt} example: `{lib}` not installed")


def make_plotly(tmp: Path) -> None:
    try:
        import plotly.graph_objects as go
    except ImportError:
        return skip("plotly_json", "plotly")
    fig = go.Figure()
    fig.add_scatter(x=YEARS, y=[co2_erf(y) for y in YEARS], name="CO₂", line=dict(color="#3E8E7E"))
    fig.add_scatter(x=YEARS, y=[volcanic_pulse(y) for y in YEARS], name="Volcanic", line=dict(color="#B5563C"))
    fig.update_layout(template="simple_white", yaxis_title="ERF (W m⁻²)", hovermode="x unified",
                      legend=dict(orientation="h", y=1.08))
    path = tmp / "overview.json"
    fig.write_json(path)
    run(["--input", str(path), "--forcing-type", "ghg", "--panel-id", "example_overview_plotly",
         "--title", "Forcing since 1850 — EXAMPLE (Plotly)",
         "--alt-text", "Interactive line chart: CO2 forcing rises steadily since 1850 while volcanic forcing shows short negative spikes.",
         "--key-message", "Greenhouse gases push steadily upward; volcanoes give short, sharp dips.",
         "--section", "overview", "--prominence", "headline", "--analysis-level", "forcing_input"])


def make_matplotlib(tmp: Path) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return skip("svg/png/pdf", "matplotlib")

    fig, ax = plt.subplots(figsize=(7, 3.4))
    ax.plot(YEARS, [co2_erf(y) for y in YEARS], color="#3E8E7E", lw=2)
    ax.set_xlabel("Year"); ax.set_ylabel("ERF (W m$^{-2}$)")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(tmp / "co2.svg")
    run(["--input", str(tmp / "co2.svg"), "--forcing-type", "ghg", "--panel-id", "example_co2_svg",
         "--title", "CO₂ forcing — EXAMPLE (matplotlib SVG)",
         "--alt-text", "Line chart of CO2 effective radiative forcing rising from zero in 1850 to about 2 W m-2 today.",
         "--key-message", "CO₂'s warming push has grown fastest since the 1960s.",
         "--section", "ghg", "--prominence", "primary", "--order", "10", "--analysis-level", "forcing_input"])

    fig, ax = plt.subplots(figsize=(6, 3))
    rate = [co2_erf(y + 1) - co2_erf(y) for y in YEARS]
    ax.bar(YEARS, rate, color="#3E8E7E", width=1)
    ax.set_ylabel("Δ ERF per year"); ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(); fig.savefig(tmp / "co2_rate.png", dpi=160)
    run(["--input", str(tmp / "co2_rate.png"), "--forcing-type", "ghg", "--panel-id", "example_co2_rate_png",
         "--title", "Year-on-year change — EXAMPLE (PNG)",
         "--alt-text", "Bar chart of the yearly increase in CO2 forcing, growing over time.",
         "--section", "ghg", "--prominence", "supporting", "--parent", "example_co2_svg",
         "--analysis-level", "forcing_input"])

    fig, axes = plt.subplots(1, 2, figsize=(8, 3.2), sharey=True)
    for ax, name, k in zip(axes, ["Myhre 1998", "Etminan 2016"], [1.0, 1.05]):
        ax.plot(YEARS, [k * co2_erf(y) for y in YEARS], color="#12303B")
        ax.set_title(name, fontsize=10); ax.spines[["top", "right"]].set_visible(False)
    axes[0].set_ylabel("ERF (W m$^{-2}$)")
    fig.suptitle("Figure 2 (synthetic)", fontsize=10); fig.tight_layout()
    fig.savefig(tmp / "paper_fig.pdf")
    run(["--input", str(tmp / "paper_fig.pdf"), "--forcing-type", "ghg", "--panel-id", "example_paper_pdf",
         "--title", "Two formulas side by side — EXAMPLE (paper PDF)",
         "--alt-text", "Two-panel figure comparing CO2 forcing from the Myhre 1998 and Etminan 2016 formulas; curves are nearly identical.",
         "--key-message", "The two formulas differ by only a few percent.",
         "--citation", "Synthetic et al. (2026), not a real paper",
         "--section", "comparisons", "--prominence", "primary", "--analysis-level", "forcing_input"])


def make_csv(tmp: Path) -> None:
    path = tmp / "co2_band.csv"
    with open(path, "w") as f:
        f.write("year,erf,erf_p05,erf_p95\n")
        for y in YEARS:
            v = co2_erf(y)
            f.write(f"{y},{v:.4f},{v * 0.88:.4f},{v * 1.12:.4f}\n")
    run(["--input", str(path), "--csv-x", "year", "--csv-y", "erf", "--csv-lo", "erf_p05", "--csv-hi", "erf_p95",
         "--x-label", "Year", "--x-unit", "CE", "--y-label", "ERF", "--y-unit", "W m-2",
         "--forcing-type", "ghg", "--panel-id", "example_co2_csv",
         "--title", "CO₂ forcing with 5–95% range — EXAMPLE (CSV)",
         "--alt-text", "Line with shaded band: CO2 forcing and its 5 to 95 percent uncertainty range.",
         "--key-message", "The uncertainty grows with the forcing itself, staying near ±12%.",
         "--section", "ghg", "--prominence", "primary", "--order", "20", "--analysis-level", "forcing_input"])


def make_animation(tmp: Path) -> None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from matplotlib.animation import FuncAnimation, FFMpegWriter, PillowWriter
    except ImportError:
        return skip("mp4/gif", "matplotlib")

    lats = [i for i in range(-90, 91, 2)]

    def field(month: int) -> list[float]:
        spread = 8 + month * 2.2
        amp = math.exp(-month / 14)
        return [amp * math.exp(-((la - 15) ** 2) / (2 * spread ** 2)) for la in lats]

    fig, ax = plt.subplots(figsize=(6, 3))
    (line,) = ax.plot(lats, field(0), color="#B5563C", lw=2)
    ax.set_ylim(0, 1.05); ax.set_xlim(-90, 90)
    ax.set_xlabel("Latitude"); ax.set_ylabel("SAOD (rel.)")
    ax.spines[["top", "right"]].set_visible(False)
    title = ax.set_title("")

    def update(m):
        line.set_ydata(field(m)); title.set_text(f"Month {m} after eruption"); return line, title

    fig.tight_layout()
    fig.savefig(tmp / "poster.png", dpi=110)
    anim = FuncAnimation(fig, update, frames=36, interval=120)

    if shutil.which("ffmpeg"):
        anim.save(tmp / "spread.mp4", writer=FFMpegWriter(fps=8, codec="libx264", extra_args=["-pix_fmt", "yuv420p", "-preset", "veryfast"]), dpi=110)
        run(["--input", str(tmp / "spread.mp4"), "--poster", str(tmp / "poster.png"),
             "--forcing-type", "volcanic", "--panel-id", "example_saod_spread_mp4",
             "--title", "How a tropical eruption's aerosol spreads — EXAMPLE (MP4)",
             "--alt-text", "Animation: a narrow aerosol peak near 15°N widens toward both poles and fades over three years.",
             "--key-message", "Within months, a tropical eruption's veil reaches both hemispheres.",
             "--section", "volcanic", "--prominence", "headline", "--analysis-level", "forcing_input"])
    else:
        skip("mp4", "ffmpeg")

    anim.save(tmp / "spread.gif", writer=PillowWriter(fps=6), dpi=70)
    run(["--input", str(tmp / "spread.gif"), "--forcing-type", "volcanic", "--panel-id", "example_saod_spread_gif",
         "--title", "Same spread as a GIF — EXAMPLE (GIF)",
         "--alt-text", "Looping animation of the aerosol peak widening and fading after an eruption.",
         "--section", "volcanic", "--prominence", "supporting", "--analysis-level", "forcing_input"])
    plt.close(fig)


def make_bokeh(tmp: Path) -> None:
    try:
        from bokeh.plotting import figure, output_file, save
        from bokeh.models import HoverTool
        from bokeh.resources import CDN
    except ImportError:
        return skip("html", "bokeh")
    p = figure(height=360, sizing_mode="stretch_width", x_axis_label="Year", y_axis_label="ERF (W m⁻²)",
               tools="pan,wheel_zoom,box_zoom,reset", toolbar_location="above")
    p.line(YEARS, [volcanic_pulse(y) for y in YEARS], color="#B5563C", line_width=2)
    p.add_tools(HoverTool(tooltips=[("year", "@x"), ("ERF", "@y{0.00}")]))
    path = tmp / "volcanic.html"
    output_file(path, title="Volcanic ERF (example)")
    save(p, resources=CDN)
    run(["--input", str(path), "--forcing-type", "volcanic", "--panel-id", "example_volcanic_bokeh",
         "--title", "Volcanic forcing pulses — EXAMPLE (Bokeh HTML)",
         "--alt-text", "Interactive line chart of volcanic forcing with negative spikes after Krakatoa, Agung, El Chichón and Pinatubo.",
         "--key-message", "Each big eruption cools for two to three years, then fades.",
         "--height", "400", "--section", "volcanic", "--prominence", "primary", "--analysis-level", "forcing_input"])


def make_notebook(tmp: Path) -> None:
    try:
        import nbformat
        from nbconvert.preprocessors import ExecutePreprocessor
        import matplotlib  # noqa: F401  (the notebook needs it)
    except ImportError:
        return skip("ipynb", "nbformat/nbconvert/matplotlib")
    nb = nbformat.v4.new_notebook()
    nb.cells = [
        nbformat.v4.new_markdown_cell("# CMIP6 vs CMIP7 volcanic forcing (synthetic example)"),
        nbformat.v4.new_code_cell("import math\nimport matplotlib.pyplot as plt\n%matplotlib inline"),
        nbformat.v4.new_code_cell(
            "years = list(range(1950, 2024))\n"
            "def pulse(y, shift=0.0):\n"
            "    e = {1963: 0.7, 1982: 0.6, 1991: 1.1}\n"
            "    return -sum(a*3*math.exp(-(y-t)/(1.2+shift)) for t, a in e.items() if y >= t)\n"
            "fig, ax = plt.subplots(figsize=(7, 3))\n"
            "ax.plot(years, [pulse(y) for y in years], label='CMIP6 (synthetic)', color='#5C7A85')\n"
            "ax.plot(years, [pulse(y, 0.3) for y in years], label='CMIP7 (synthetic)', color='#B5563C')\n"
            "ax.set_ylabel('ERF (W m$^{-2}$)'); ax.legend(frameon=False)\n"
            "ax.spines[['top','right']].set_visible(False)\n"
            "plt.show()"
        ),
    ]
    ExecutePreprocessor(timeout=120, kernel_name="python3").preprocess(nb, {"metadata": {"path": str(tmp)}})
    path = tmp / "cmip_compare.ipynb"
    nbformat.write(nb, path)
    run(["--input", str(path), "--forcing-type", "volcanic", "--panel-id", "example_cmip_compare_ipynb",
         "--title", "CMIP6 vs CMIP7 volcanic forcing — EXAMPLE (notebook)",
         "--alt-text", "Two lines comparing synthetic CMIP6 and CMIP7 volcanic forcing; CMIP7 recovers slightly more slowly.",
         "--key-message", "In this demo, CMIP7's eruptions fade a little more slowly than CMIP6's.",
         "--section", "comparisons", "--prominence", "primary", "--analysis-level", "forcing_input"])


def clean() -> None:
    n = 0
    for p in list((REPO / "site" / "panels").rglob("example_*.json")) + list((REPO / "site" / "assets").rglob("example_*")):
        p.unlink(); n += 1
    print(f"removed {n} example file(s)")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--clean", action="store_true", help="delete the example panels and assets")
    args = ap.parse_args()
    if args.clean:
        clean()
        return 0
    with tempfile.TemporaryDirectory() as d:
        tmp = Path(d)
        for maker in (make_plotly, make_matplotlib, make_csv, make_animation, make_bokeh, make_notebook):
            maker(tmp)
    print("\nDone. Next: python scripts/validate_panel.py && python scripts/build_manifest.py --include-drafts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
